-- ============================================================================
-- ONE-TIME ADMIN SETUP (run in a Snowsight worksheet as ACCOUNTADMIN).
-- Replace <AWS_ROLE_ARN>, <BUCKET> and <PASSWORD> before running.
-- This file is NOT executed by the pipeline.
-- ============================================================================
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS FIN_ETL_ROLE;

CREATE WAREHOUSE IF NOT EXISTS FIN_ETL_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS FIN_SCRAPER;
CREATE SCHEMA IF NOT EXISTS FIN_SCRAPER.STAGING;
CREATE SCHEMA IF NOT EXISTS FIN_SCRAPER.CORE;
CREATE SCHEMA IF NOT EXISTS FIN_SCRAPER.REPORTING;
CREATE SCHEMA IF NOT EXISTS FIN_SCRAPER.OPS;

GRANT USAGE ON WAREHOUSE FIN_ETL_WH TO ROLE FIN_ETL_ROLE;
GRANT ALL PRIVILEGES ON DATABASE FIN_SCRAPER TO ROLE FIN_ETL_ROLE;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE FIN_SCRAPER TO ROLE FIN_ETL_ROLE;

CREATE USER IF NOT EXISTS FIN_ETL_USER
  PASSWORD = '<PASSWORD>'
  DEFAULT_ROLE = FIN_ETL_ROLE
  DEFAULT_WAREHOUSE = FIN_ETL_WH
  MUST_CHANGE_PASSWORD = FALSE;
GRANT ROLE FIN_ETL_ROLE TO USER FIN_ETL_USER;

-- Keyless S3 access: Snowflake assumes an IAM role in your AWS account.
CREATE STORAGE INTEGRATION IF NOT EXISTS FIN_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = '<AWS_ROLE_ARN>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<BUCKET>/raw/');

-- Copy STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID from this output into the
-- trust policy of the IAM role above (see README).
DESC INTEGRATION FIN_S3_INT;

GRANT USAGE ON INTEGRATION FIN_S3_INT TO ROLE FIN_ETL_ROLE;

USE ROLE FIN_ETL_ROLE;
USE DATABASE FIN_SCRAPER;

CREATE FILE FORMAT IF NOT EXISTS STAGING.PARQUET_FF
  TYPE = PARQUET
  USE_LOGICAL_TYPE = TRUE;

CREATE STAGE IF NOT EXISTS STAGING.S3_RAW_STAGE
  URL = 's3://<BUCKET>/raw/'
  STORAGE_INTEGRATION = FIN_S3_INT
  FILE_FORMAT = STAGING.PARQUET_FF;

-- Smoke test (after the first pipeline run):  LIST @STAGING.S3_RAW_STAGE;
